/**
 * One sourcemap fixture case.
 *
 * `why` names the hazard in one line and is not decoration: a failing
 * `it.each` prints the id, and the id is only useful next to the reason the
 * case exists. Deliberately the same three-field shape as `HostileCase` in
 * `hostile.fixture.ts`, so a consumer that iterates one can iterate the other.
 */
export type MapFixtureCase = {
  readonly id: string;
  readonly why: string;
  readonly value: string;
};

