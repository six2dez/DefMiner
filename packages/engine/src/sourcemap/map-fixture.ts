// packages/engine/src/sourcemap/map-fixture.ts — THE sourcemap corpus. One module.
//
// ===========================================================================
// ONE FIXTURE, THREE CONSUMERS. A SECOND ONE IS THE DEFECT THIS PREVENTS.
// ===========================================================================
// The reason it is one module and not three copies is not tidiness. Two fixtures
// is how two surfaces come to assert different things about the same attack, and
// how the one that is wrong stays wrong: nobody diffs two test corpora. Every
// consumer imports from here, and every consumer asserts it covered the
// relevant `*_CASE_IDS` array IN FULL — a fixture that grows a case some spec
// silently iterates past is a fixture that proves less each time it is extended.
//
// CONSUMERS, named so a reader knows what an edit here reaches:
//   tests/corpus-maps.spec.ts             (this plan — the fixture's own gate)
//   the MAP-05 hostile-map suite          (plan 07-02)
//   the retained traversal-sink gate      (plan 07-03)
// Extend these arrays; do not fork them.
//
// ===========================================================================
// WHY THE BYTES LIVE HERE AND NOT UNDER `corpus/`
// ===========================================================================
// RESEARCH § O-03 says to commit the map fixtures under `corpus/maps/` with a
// sha256 gate. THAT INSTRUCTION IS NOT FOLLOWED, and the reason is mechanical:
// `corpus/` is gitignored IN ITS ENTIRETY (`.gitignore:9` — check it with
// `git check-ignore -v corpus/`). Bytes written there do not survive a clean
// checkout, so a fixture placed there is a claim rather than an artifact.
//
// The corpus splits by SIZE across the two homes that ARE tracked:
//
//   LARGE real maps (megabyte scale, needed only by the D-10 probe) live in
//   `scripts/phase7/fetch-maps.sh` with committed SHA-256 hashes, in the
//   `scripts/spike/fetch-corpus.sh` idiom. The script and the hashes are the
//   reproducible artifact; the ~37 MB of vendor JSON is not.
//
//   SMALL hostile and structural fixtures — needed by CI on EVERY COMMIT, with
//   NO NETWORK — live HERE as string literals, in the `hostile.fixture.ts`
//   idiom. That is why this file exists at all.
//
// ===========================================================================
// EVERYTHING HERE IS A STRING LITERAL, AND EVERY ADVERSARIAL CHARACTER IS AN
// ESCAPE SEQUENCE
// ===========================================================================
// `packages/backend/src/outbound-prohibition.spec.ts` walks BOTH source roots
// with the TypeScript parser and `packages/engine/src` is one of them. This file
// is not a `.spec.ts`, so it IS scanned. The payloads below are STRING LITERALS,
// never call expressions, so a hostile map reads as data to an AST walk exactly
// as it must read as data to a parser. Do not "improve" a case into executable
// code, and do not replace a document with `JSON.stringify` of an object — the
// point of several cases is text a JSON serialiser would never produce.
//
// Adversarial characters are written as ESCAPES rather than literals. A literal
// C0 control or RIGHT-TO-LEFT OVERRIDE in a source file is invisible in every
// diff and every review tool, and this corpus is entirely about characters that
// are invisible.
//
// The `value` of a case is the document or the label AS DELIVERED — the bytes a
// parser or a renderer would actually receive — not a parsed object. Several
// cases (the XSSI prefix, the truncated document) are not valid JSON at all, and
// that is the case.

